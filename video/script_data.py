"""Narration for every video. One entry in VIDEOS per video; the name is what you pass to build.sh.

Each segment is (scene id, spoken text, caption text, pause after in seconds).
  - The scene id matches <section class="scene" id="s-<scene id>"> in <video>.html.
  - "|" splits a segment into phrases. Spoken and caption text must have the same number of
    phrases: each caption is shown exactly while its phrase is spoken, and the page can time
    animations to a phrase with data-at="p0", "p1", ...
  - Spoken text is what the voice reads, so spell out what it would otherwise stumble on
    ("thirty", "A.I.", "T.L.S."). Caption text is what the viewer reads ("30", "AI", "TLS").
"""

VIDEOS = {
    "example": [
        ("hook", "This video was made entirely with code.|No camera. No editing software.",
         "This video was made entirely with code.|No camera. No editing software.", 0.5),
        ("how", "Here is how it works.|You write the narration as plain text.|A voice model on your own computer reads it out loud.|And every scene is a web page, animated in time with the voice.",
         "Here is how it works.|You write the narration as plain text.|A voice model on your own computer reads it out loud.|And every scene is a web page, animated in time with the voice.", 0.5),
        ("data", "It renders at thirty frames per second.|Numbers can count up, and bars can grow.|And the captions follow every phrase.",
         "It renders at 30 frames per second.|Numbers can count up, and bars can grow.|And the captions follow every phrase.", 0.5),
        ("close", "Change the script, run one command,|and you have a new video.",
         "Change the script, run one command,|and you have a new video.", 1.6),
    ],
}

# Optional sound effects, per video: (sound, scene id, phrase index, offset in s, gain).
# Sounds: "pop", "ding", "buzz", "thud", "whoosh". Offset and gain may be left out (0 and 1).
# A whoosh is always added at every scene change.
CUES = {
    "example": [
        ("thud", "hook", 0, 0.0, 0.6),
        ("pop", "how", 1), ("pop", "how", 2), ("pop", "how", 3),
        ("ding", "data", 0, 0.9, 0.7), ("pop", "data", 1), ("pop", "data", 1, 0.9),
        ("ding", "close", 1, 0.0, 0.9), ("thud", "close", 1, 0.0, 0.6),
    ],
}

# Optional: which of the four built-in chord progressions the background music uses (0-3).
MUSIC = {"example": 0}

# Videos generated by run.py keep their script next to their scenes, in build/<name>_script.json.
import json, pathlib
for _file in sorted((pathlib.Path(__file__).resolve().parent / "build").glob("*_script.json")):
    _name, _data = _file.name[:-len("_script.json")], json.loads(_file.read_text(encoding="utf-8"))
    VIDEOS[_name] = [tuple(s) for s in _data["segments"]]
    CUES[_name] = [tuple(c) for c in _data.get("cues", [])]
    MUSIC[_name] = _data.get("music", 0)
