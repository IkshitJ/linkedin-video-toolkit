"""Build one narrated video: voice -> frames -> music and effects -> out/<video>.mp4

usage: python video/build.py <video> [voice] [speed]        (with the Python of .venv)
       video/build.sh <video> [voice] [speed]               (the same, on macOS and Linux)

<video> is an entry of VIDEOS in script_data.py with its scenes in video/<video>.html, or a video
generated by run.py (script and scenes in video/build/). Example: python video/build.py example
"""
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT.parent / "out"


def build(vid, voice="am_michael", speed="1.0"):
    """-> the finished MP4. Raises SystemExit or CalledProcessError if a step fails."""
    if not ((ROOT / (vid + ".html")).exists() or (ROOT / "build" / (vid + ".html")).exists()):
        raise SystemExit("no video/%s.html" % vid)
    for step in (["tts.py", vid, voice, str(speed)], ["render.py", vid], ["mix.py", vid]):
        subprocess.run([sys.executable, str(ROOT / step[0])] + step[1:], cwd=str(ROOT), check=True)
    import imageio_ffmpeg
    OUT.mkdir(exist_ok=True)
    out = OUT / (vid + ".mp4")
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-loglevel", "error", "-y",
                    "-i", str(ROOT / "build" / (vid + "_silent.mp4")), "-i", str(ROOT / "build" / (vid + "_mix.wav")),
                    "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", str(out)], check=True)
    print("wrote", out)
    return out


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    try:
        build(*sys.argv[1:4])
    except subprocess.CalledProcessError as err:
        sys.exit(err.returncode or 1)
