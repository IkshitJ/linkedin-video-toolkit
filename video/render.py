"""Render <video>.html frame by frame (deterministic seek) to build/<video>_silent.mp4, or dump preview stills.
usage: render.py <video>             full render at 30 fps
       render.py <video> t1 t2 ...   stills at those times (seconds) into build/preview/

The frame size is 1920x1080 unless the page says otherwise in its <head>:
    <meta name="video-size" content="1080x1350">"""
import asyncio, json, pathlib, re, subprocess, sys
import imageio_ffmpeg
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parent
BUILD = ROOT / "build"
sys.path.insert(0, str(ROOT.parent))
from toolkit.browser import launch_renderer   # Chrome, else Edge, else Playwright's Chromium
if len(sys.argv) < 2:
    sys.exit(__doc__)
vid, times = sys.argv[1], [float(x) for x in sys.argv[2:]]
FPS = 30
html = ROOT / f"{vid}.html"
if not html.exists():
    html = BUILD / f"{vid}.html"   # a video generated by run.py keeps its scenes in build/
size = re.search(r'<meta\s+name="video-size"\s+content="(\d+)x(\d+)"', html.read_text(encoding="utf-8"))
W, H = (int(size[1]), int(size[2])) if size else (1920, 1080)
if not (BUILD / f"{vid}_timeline.json").exists():
    sys.exit(f"no timeline for {vid}: run tts.py {vid} first")
tl = json.load(open(BUILD / f"{vid}_timeline.json"))
(BUILD / f"{vid}_timeline.js").write_text("window.TL = " + json.dumps(tl) + ";")


async def main():
    async with async_playwright() as pw:
        browser = await launch_renderer(pw, ["--hide-scrollbars", "--force-color-profile=srgb"])
        page = await (await browser.new_context(viewport={"width": W, "height": H}, device_scale_factor=1)).new_page()
        page.on("pageerror", lambda e: print("PAGEERROR", e, flush=True))
        await page.goto(html.as_uri())
        await page.evaluate("window.READY")
        if times:
            (BUILD / "preview").mkdir(exist_ok=True)
            for t in times:
                await page.evaluate("t => window.seek(t)", t)
                still = BUILD / f"preview/{vid}_{t:06.2f}.jpg"
                await page.screenshot(path=str(still), type="jpeg", quality=70)
                print("wrote", still)
            await browser.close(); return
        out = BUILD / f"{vid}_silent.mp4"
        ff = subprocess.Popen([imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-loglevel", "error", "-y", "-f", "image2pipe", "-c:v", "mjpeg",
            "-framerate", str(FPS), "-i", "-", "-vf", "scale=in_range=pc:out_range=tv:out_color_matrix=bt709,format=yuv420p",
            "-c:v", "libx264", "-preset", "medium", "-crf", "17", "-color_range", "tv", "-colorspace", "bt709", "-color_primaries", "bt709",
            "-color_trc", "bt709", "-r", str(FPS), "-movflags", "+faststart", "-an", str(out)], stdin=subprocess.PIPE)
        n = int(tl["duration"] * FPS)
        for i in range(n):
            await page.evaluate("t => window.seek(t)", i / FPS)
            ff.stdin.write(await page.screenshot(type="jpeg", quality=95))
            if i % 300 == 0: print(f"{i}/{n}", flush=True)
        ff.stdin.close()
        assert ff.wait() == 0
        await browser.close()
        print("wrote", out)

asyncio.run(main())
